import CoreGraphics

// Temporary event observation used by safelyEnforceActiveState; not the
// enforcer's three-byte application state. Native field names are unavailable.
struct SafeActivationObservedEvents {
    private(set) var transitionFlags: UInt16 = 0
    private(set) var lastEventTime: Double = 0

    mutating func filter(type: CGEventType, event: CGEvent, time: Double) -> CGEvent? {
        // Pinned native optional CGEventField is present and equals 83.
        let subtype = event.getIntegerValueField(CGEventField(rawValue: 83)!)
        return observe(type: type.rawValue, subtypeValue: subtype, time: time) ? event : nil
    }

    // 0x100745044. true means return the original event; false suppresses it.
    // Caller serializes access (the source takes an unfair lock).
    mutating func observe(type: UInt32, subtypeValue: Int64?, time: Double) -> Bool {
        lastEventTime = time
        let subtype = subtypeValue.flatMap(Int16.init(exactly:))
        if type == 20 || (type == 13 && subtype == 1) {
            transitionFlags = 0x0101
            return false
        }
        if type == 19 || (type == 13 && subtype == 2) {
            transitionFlags |= 1
            return false
        }
        if type == 13 && (subtype == 22 || subtype == 23) { return false }
        return true
    }
}

// 0x100745330: events generated by this helper pass through. Other sources
// targeting the temporarily activated app are reposted to the saved foreground
// application and consumed. Timestamp is retained (unlike synthesized input).
func routeInputDuringSafeActivation(
    _ event: CGEvent, helperPID: Int32, targetPID: Int32,
    previousApplicationPID: () -> Int32,
    post: (CGEvent, Int32) -> Void
) -> CGEvent? {
    let source = event.getIntegerValueField(.eventSourceUnixProcessID)
    let sourcePID = Int32(source) // Source uses checked conversion as well.
    if sourcePID == helperPID { return event }
    let target = Int32(event.getIntegerValueField(.eventTargetUnixProcessID))
    guard target == targetPID else { return event }
    post(event, previousApplicationPID())
    return nil
}
