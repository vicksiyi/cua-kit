import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
export async function assembleKernelWorker() {
  const result = await build({
    entryPoints: ["packages/browser-extension/src/kernel_worker_entry.ts"],
    bundle: true, platform: "browser", format: "iife", write: false,
    // Resolve reconstructed source directly, before this build emits workspace dist.
    alias: {
      "@core/core/browserRpcPeer": resolve("packages/core/src/browser_rpc_peer.ts"),
      "@core/browser/kernelBrowserRuntime": resolve("packages/browser/src/kernel_browser_runtime.ts"),
    },
  });
  const target = "packages/browser-extension/src/kernel_worker_source.ts";
  const content = `// Generated by scripts/assemble-kernel-worker.mjs from reconstructed TypeScript.\nexport const kernelWorkerSource = ${JSON.stringify(result.outputFiles[0].text)};\n`;
  if (await readFile(target, "utf8").catch(() => undefined) !== content) await writeFile(target, content);
}
